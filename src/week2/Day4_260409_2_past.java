package week2;

import java.util.*;

/**
 * 문제: [PCCP 기출문제] 1번 / 붕대 감기
 *
 * 어떤 게임에 "붕대 감기" 기술이 있습니다.
 * - 붕대 감기는 t초 동안 붕대를 감으면서 1초마다 x만큼 체력을 회복합니다.
 * - t초 연속으로 붕대를 감는 데 성공하면 y만큼 체력을 추가로 회복합니다.
 * - 캐릭터의 체력은 최대 체력을 넘을 수 없습니다.
 *
 * 기술 시전 도중 몬스터에게 공격을 당하면:
 * - 기술이 즉시 취소되고, 공격을 당하는 그 순간에는 체력 회복이 일어나지 않습니다.
 * - 기술이 취소되거나 끝나면, 그 즉시 붕대 감기를 다시 사용하며
 *   연속 성공 시간은 0으로 초기화됩니다.
 *
 * 몬스터 공격을 받아 현재 체력이 0 이하가 되면 캐릭터는 사망합니다.
 *
 * 모든 공격이 끝난 직후의 남은 체력을 반환하세요.
 * 캐릭터가 도중에 죽는다면 -1을 반환합니다.
 *
 * [제한 사항]
 * - bandage = [t, x, y]
 *     1 ≤ t ≤ 50, 1 ≤ x ≤ 100, 1 ≤ y ≤ 100
 * - 1 ≤ health ≤ 1,000
 * - 1 ≤ attacks.length ≤ 100
 * - attacks[i] = [공격 시간, 피해량]
 * - attacks는 공격 시간 오름차순, 공격 시간은 모두 다름
 * - 1 ≤ 공격 시간 ≤ 1,000, 1 ≤ 피해량 ≤ 100
 *
 * [예시로 이해하기]
 * 입력: bandage = [5, 1, 5], health = 30, attacks = [[2,10],[9,15],[10,5],[11,5]]
 * → 시전시간 t=5, 초당 회복 x=1, 5초 연속 성공 시 보너스 y=5
 *
 *  시간 |  체력(변화)  | 연속성공 | 공격 | 설명
 *  -----|--------------|----------|------|------------------------------------------
 *    0  |  30          |    0     |  X   | 초기 상태 (최대 체력 = 30)
 *    1  |  30  (+0)    |    1     |  X   | 이미 최대 체력이라 회복은 30으로 캡
 *    2  |  20 (-10)    |    0     |  O   | 공격! 연속성공 초기화
 *    3  |  21  (+1)    |    1     |  X   | 회복 +1
 *    4  |  22  (+1)    |    2     |  X   |
 *    5  |  23  (+1)    |    3     |  X   |
 *    6  |  24  (+1)    |    4     |  X   |
 *    7  |  30  (+6)    |   5→0    |  X   | 5초 연속 성공! +1 회복 후 보너스 +5 → 30 캡
 *    8  |  30  (+0)    |    1     |  X   | 회복은 일어나지만 이미 최대 체력
 *    9  |  15 (-15)    |    0     |  O   | 공격
 *   10  |  10  (-5)    |    0     |  O   | 공격
 *   11  |   5  (-5)    |    0     |  O   | 마지막 공격, 생존 → 결과 = 5
 *
 * 포인트:
 * - "공격당한 초"에는 회복이 일어나지 않음 (그 초는 공격 처리만)
 * - "t초 연속 성공"은 매초 회복 +x가 먼저 발생하고, 그 후 보너스 +y를 더함
 * - 체력은 매번 최대 체력을 넘지 않도록 캡
 *
 * [힌트]
 * - 시뮬레이션 문제. 1초부터 마지막 공격 시간까지 초 단위로 돌면 충분함 (최대 1,000번).
 * - 상태 변수:
 *     int hp;          // 현재 체력
 *     int combo;       // 연속 성공 시간 (매초 회복 시 +1, 공격/보너스 시 0)
 * - 다음 공격 시간을 빠르게 꺼내려면 공격 배열의 인덱스를 0부터 하나씩 소비하거나,
 *   공격 시간 → 피해량 맵(Map<Integer,Integer>)을 만들어도 됨.
 * - 매초 처리 순서:
 *     1) 이 시각이 공격 시간인지 확인
 *     2) 공격이면: hp -= 피해량, combo = 0, hp <= 0이면 즉시 -1 반환
 *     3) 공격이 아니면: hp += x, combo += 1
 *                       combo == t면 hp += y, combo = 0
 *                       hp가 최대 체력 초과하면 최대 체력으로 캡(cap)
 * - 마지막 공격 시간까지만 시뮬레이션하면 됨 (그 이후엔 회복해도 의미 없음).
 * - Math.min 으로 최대 체력 캡 걸면 코드가 깔끔해짐.
 *
 * @param bandage [t, x, y]
 * @param health 최대 체력
 * @param attacks [[공격 시간, 피해량], ...]
 * @return 남은 체력 또는 -1
 */
public class Day4_260409_2_past {
    // 입력: bandage = [5, 1, 5], health = 30, attacks = [[2,10],[9,15],[10,5],[11,5]]
    public static int solution(int[] bandage, int health, int[][] attacks) {
        int hp = health;
        int combo = 0;
        int idx = 0;
        // 마지막 공격 시간까지만 돈다.
        int lastAttackTime = attacks[attacks.length-1][0];
        for(int i = 1; i <= lastAttackTime; i++) {
            // 공격 시간이라면
            if(idx < attacks.length && attacks[idx][0] == i) {
                hp -= attacks[idx][1];
                if (hp <= 0) return -1;
                combo = 0;
                idx++;
            } else { // 공격 시간이 아니라면
                hp += bandage[1];
                combo++;
                if(combo == bandage[0]) {
                    hp += bandage[2];
                    combo = 0;
                }
                hp = Math.min(hp, health);
            }
        }
        return hp;
    }

    public static void main(String[] args) {
        // 테스트 1: 예제 #1 — 회복으로 최대 체력까지 돌아옴
        int r1 = solution(
            new int[]{5, 1, 5},
            30,
            new int[][]{{2, 10}, {9, 15}, {10, 5}, {11, 5}}
        );
        System.out.printf("테스트 1: %s (결과: %d, 기대: 5)%n", r1 == 5 ? "PASS" : "FAIL", r1);

        // 테스트 2: 예제 #2 — 마지막 공격에서 사망
        int r2 = solution(
            new int[]{3, 2, 7},
            20,
            new int[][]{{1, 15}, {5, 16}, {8, 6}}
        );
        System.out.printf("테스트 2: %s (결과: %d, 기대: -1)%n", r2 == -1 ? "PASS" : "FAIL", r2);

        // 테스트 3: 예제 #3 — 시전 시간이 달라서 보너스를 못 받고 사망
        int r3 = solution(
            new int[]{4, 2, 7},
            20,
            new int[][]{{1, 15}, {5, 16}, {8, 6}}
        );
        System.out.printf("테스트 3: %s (결과: %d, 기대: -1)%n", r3 == -1 ? "PASS" : "FAIL", r3);

        // 테스트 4: 예제 #4 — 시전 시간 1 (매초 보너스)
        int r4 = solution(
            new int[]{1, 1, 1},
            5,
            new int[][]{{1, 2}, {3, 2}}
        );
        System.out.printf("테스트 4: %s (결과: %d, 기대: 3)%n", r4 == 3 ? "PASS" : "FAIL", r4);

        // 테스트 5: 엣지 — 공격 1회, 즉사
        int r5 = solution(
            new int[]{5, 1, 5},
            10,
            new int[][]{{1, 100}}
        );
        System.out.printf("테스트 5: %s (결과: %d, 기대: -1)%n", r5 == -1 ? "PASS" : "FAIL", r5);

        // 테스트 6: 엣지 — 공격이 마지막 시각 1회, 그 전까지 풀피 유지
        // 1초~4초는 회복(이미 풀피라 캡), 5초에 공격 5 피해 → hp=5
        int r6 = solution(
            new int[]{2, 1, 3},
            10,
            new int[][]{{5, 5}}
        );
        System.out.printf("테스트 6: %s (결과: %d, 기대: 5)%n", r6 == 5 ? "PASS" : "FAIL", r6);
    }
}
